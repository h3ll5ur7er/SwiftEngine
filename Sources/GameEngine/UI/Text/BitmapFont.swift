import Foundation


/// A bitmap font for rendering text
/// 
/// Uses a sprite sheet containing a grid of character glyphs.
/// Default layout assumes ASCII characters starting from space (32).
@MainActor
public final class BitmapFont {
    /// The texture containing all glyphs
    public let texture: Texture
    
    /// Width of each character cell in pixels
    public let charWidth: Int
    
    /// Height of each character cell in pixels
    public let charHeight: Int
    
    /// Number of characters per row in the sprite sheet
    public let charsPerRow: Int
    
    /// First ASCII character in the font (default: 32 = space)
    public let firstChar: Int
    
    /// Number of characters in the font
    public let charCount: Int
    
    /// Optional per-character width overrides for variable-width fonts
    public var charWidths: [Int: Int] = [:]
    
    /// Default spacing between characters
    public var spacing: Int = 1
    
    /// Create a bitmap font from a texture
    /// 
    /// - Parameters:
    ///   - texture: The sprite sheet containing character glyphs
    ///   - charWidth: Width of each character cell
    ///   - charHeight: Height of each character cell
    ///   - charsPerRow: Number of characters per row in the sprite sheet
    ///   - firstChar: ASCII code of the first character (default: 32 = space)
    ///   - charCount: Total number of characters (default: 95 = printable ASCII)
    public init(
        texture: Texture,
        charWidth: Int,
        charHeight: Int,
        charsPerRow: Int,
        firstChar: Int = 32,
        charCount: Int = 95
    ) {
        self.texture = texture
        self.charWidth = charWidth
        self.charHeight = charHeight
        self.charsPerRow = charsPerRow
        self.firstChar = firstChar
        self.charCount = charCount
    }
    
    /// Load a bitmap font from a BMP file
    public static func load(
        from path: String,
        charWidth: Int,
        charHeight: Int,
        charsPerRow: Int,
        firstChar: Int = 32,
        charCount: Int = 95
    ) -> BitmapFont? {
        guard let texture = BMPLoader.load(from: path) else {
            return nil
        }
        return BitmapFont(
            texture: texture,
            charWidth: charWidth,
            charHeight: charHeight,
            charsPerRow: charsPerRow,
            firstChar: firstChar,
            charCount: charCount
        )
    }
    
    /// Get the source rectangle for a character in the sprite sheet
    public func sourceRect(for char: Character) -> Rect? {
        guard let ascii = char.asciiValue else { return nil }
        let index = Int(ascii) - firstChar
        guard index >= 0 && index < charCount else { return nil }
        
        let col = index % charsPerRow
        let row = index / charsPerRow
        
        return Rect(
            x: Int32(col * charWidth),
            y: Int32(row * charHeight),
            width: Int32(charWidth),
            height: Int32(charHeight)
        )
    }
    
    /// Get the effective width of a character (for variable-width fonts)
    public func widthOf(_ char: Character) -> Int {
        guard let ascii = char.asciiValue else { return charWidth }
        return charWidths[Int(ascii)] ?? charWidth
    }
    
    /// Measure the size of a text string
    public func measureText(_ text: String, scale: Int = 1) -> (width: Int, height: Int) {
        var width = 0
        var maxWidth = 0
        var lines = 1
        
        for char in text {
            if char == "\n" {
                maxWidth = max(maxWidth, width)
                width = 0
                lines += 1
            } else {
                width += widthOf(char) * scale + spacing * scale
            }
        }
        
        maxWidth = max(maxWidth, width)
        if maxWidth > 0 {
            maxWidth -= spacing * scale  // Remove trailing spacing
        }
        
        return (maxWidth, lines * charHeight * scale)
    }
    
    /// Draw text at the given position
    public func drawText(
        _ text: String,
        x: Int32,
        y: Int32,
        color: Color,
        scale: Int = 1,
        renderer: Renderer
    ) {
        let screenWidth = Int(renderer.width)
        let screenHeight = Int(renderer.height)
        
        var cursorX = Int(x)
        var cursorY = Int(y)
        
        for char in text {
            if char == "\n" {
                cursorX = Int(x)
                cursorY += charHeight * scale
                continue
            }
            
            guard let srcRect = sourceRect(for: char) else {
                cursorX += charWidth * scale + spacing * scale
                continue
            }
            
            // Draw the character
            drawGlyph(
                srcRect: srcRect,
                destX: cursorX,
                destY: cursorY,
                color: color,
                scale: scale,
                screenWidth: screenWidth,
                screenHeight: screenHeight
            )
            
            cursorX += widthOf(char) * scale + spacing * scale
        }
    }
    
    /// Draw a single glyph from the sprite sheet using Primitives
    private func drawGlyph(
        srcRect: Rect,
        destX: Int,
        destY: Int,
        color: Color,
        scale: Int,
        screenWidth: Int,
        screenHeight: Int
    ) {
        let srcX = Int(srcRect.x)
        let srcY = Int(srcRect.y)
        let srcW = Int(srcRect.width)
        let srcH = Int(srcRect.height)
        
        for py in 0..<srcH {
            for px in 0..<srcW {
                // Sample the font texture
                let texColor = texture.getPixel(x: srcX + px, y: srcY + py)
                
                // Skip transparent/dark pixels (font background)
                // Assuming white-on-black or similar font where bright = glyph
                let brightness = Int(texColor.r) + Int(texColor.g) + Int(texColor.b)
                if brightness < 128 * 3 { continue }
                
                // Draw scaled pixel using Primitives
                for sy in 0..<scale {
                    for sx in 0..<scale {
                        let screenX = Int32(destX + px * scale + sx)
                        let screenY = Int32(destY + py * scale + sy)
                        
                        guard screenX >= 0 && screenX < Int32(screenWidth) &&
                              screenY >= 0 && screenY < Int32(screenHeight) else { continue }
                        
                        Primitives.drawPixel(screenX, screenY, color)
                    }
                }
            }
        }
    }
}

// MARK: - Built-in Font Generation

extension BitmapFont {
    /// Generate a simple built-in bitmap font texture
    /// This creates a basic 8x8 pixel font with ASCII characters
    @MainActor
    public static func createBuiltinFont() -> BitmapFont {
        let charWidth = 6
        let charHeight = 8
        let charsPerRow = 16
        let charCount = 95  // Printable ASCII (32-126)
        
        let rows = (charCount + charsPerRow - 1) / charsPerRow
        let texWidth = charsPerRow * charWidth
        let texHeight = rows * charHeight
        
        let texture = Texture(width: texWidth, height: texHeight)
        
        // Fill with black background
        texture.fill(with: .black)
        
        // Draw each character
        for i in 0..<charCount {
            let char = Character(UnicodeScalar(32 + i)!)
            let col = i % charsPerRow
            let row = i / charsPerRow
            let baseX = col * charWidth
            let baseY = row * charHeight
            
            if let bitmap = getCharBitmap(char) {
                for (py, rowBits) in bitmap.enumerated() {
                    for px in 0..<charWidth {
                        if (rowBits >> (charWidth - 1 - px)) & 1 == 1 {
                            texture.setPixel(x: baseX + px, y: baseY + py, color: .white)
                        }
                    }
                }
            }
        }
        
        return BitmapFont(
            texture: texture,
            charWidth: charWidth,
            charHeight: charHeight,
            charsPerRow: charsPerRow
        )
    }
    
